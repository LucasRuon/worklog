import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { realpathSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { test } from 'node:test';
import { fixture } from '../helpers.js';
import { listProjects, registerProjectRoot } from '../../src/core/projects.js';
import { listCommits, scanCommits } from '../../src/collectors/git.js';

test('Git: importação idempotente, clones/worktrees, rename NUL, merge e histórico reescrito', async () => {
  const f = await fixture();
  const git = (path: string, ...args: string[]) => execFileSync('git', ['-C', path, ...args], { encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_NAME: 'Autora Á', GIT_AUTHOR_EMAIL: 'author@example.test', GIT_COMMITTER_NAME: 'Committer', GIT_COMMITTER_EMAIL: 'committer@example.test', GIT_AUTHOR_DATE: '2026-11-05T12:00:00Z', GIT_COMMITTER_DATE: '2026-11-05T12:01:00Z' } }).trim();
  try {
    git(f.root, 'init', '-q', '-b', 'main');
    git(f.root, 'remote', 'add', 'origin', 'https://example.test/team/test.git');
    const filename = 'arquivo á\ncom espaço.txt';
    await writeFile(join(f.root, filename), 'one');
    await writeFile(join(f.root, '.env'), 'PRIVATE=secret');
    git(f.root, 'add', '.'); git(f.root, 'commit', '-qm', 'Primeiro\n\nMensagem completa');
    const first = git(f.root, 'rev-parse', 'HEAD');
    registerProjectRoot(f.ctx, { projectName: 'Teste Git', path: f.root, deviceId: f.ctx.config.deviceId });
    const root = listProjects(f.ctx).find((p) => p.id === f.projectId)!.roots[0]!;
    assert.equal((await scanCommits(f.ctx, root)).inserted, 1);
    assert.equal((await scanCommits(f.ctx, root)).inserted, 0);
    let commits = listCommits(f.ctx, f.filter);
    assert.equal(commits.length, 1); assert.equal(commits[0]!.authorName, 'Autora Á');
    assert.equal(commits[0]!.message, 'Primeiro\n\nMensagem completa\n');
    assert.deepEqual(commits[0]!.files.map((file) => file.path), [filename]);
    assert.equal(JSON.stringify(commits).includes('.env'), false);
    const clone = join(f.directory, 'clone'); git(f.directory, 'clone', '-q', f.root, clone);
    git(clone, 'remote', 'set-url', 'origin', 'git@example.test:team/test.git');
    registerProjectRoot(f.ctx, { projectName: 'Clone', path: clone, deviceId: f.ctx.config.deviceId });
    const cloneRoot = listProjects(f.ctx).flatMap((p) => p.roots).find((r) => r.path === realpathSync(clone))!;
    assert.equal((await scanCommits(f.ctx, cloneRoot)).inserted, 0);
    assert.equal(listCommits(f.ctx, f.filter).length, 1);
    git(f.root, 'mv', filename, 'novo á.txt'); git(f.root, 'commit', '-qm', 'Renomeia');
    const renamed = git(f.root, 'rev-parse', 'HEAD');
    await scanCommits(f.ctx, root);
    assert.equal(listCommits(f.ctx, f.filter).find((c) => c.sha === renamed)!.files[0]!.previousPath, filename);
    const worktree = join(f.directory, 'worktree'); git(f.root, 'worktree', 'add', '-qb', 'side', worktree);
    registerProjectRoot(f.ctx, { projectName: 'Worktree', path: worktree, deviceId: f.ctx.config.deviceId });
    await writeFile(join(worktree, 'side.txt'), 'side'); git(worktree, 'add', '.'); git(worktree, 'commit', '-qm', 'Lateral');
    git(f.root, 'merge', '--no-ff', 'side', '-qm', 'Merge');
    await scanCommits(f.ctx, root);
    const merge = listCommits(f.ctx, f.filter).find((c) => c.parents.length === 2)!;
    assert.ok(merge); assert.equal(merge.files[0]!.path, 'side.txt');
    git(f.root, 'reset', '--hard', first);
    // O worktree ainda observa side; a raiz main precisa refletir somente seus refs atuais.
    git(f.root, 'worktree', 'remove', '--force', worktree);
    git(f.root, 'branch', '-D', 'side');
    await scanCommits(f.ctx, root);
    commits = listCommits(f.ctx, f.filter);
    assert.equal(commits.find((c) => c.sha === merge.sha)!.origins.find((o) => o.rootId === root.id)!.reachable, false);
    assert.equal(commits.find((c) => c.sha === first)!.origins.length, 2);
    assert.deepEqual(listCommits(f.ctx, { ...f.filter, tools: ['opencode'] }), []);
    assert.deepEqual(listCommits(f.ctx, { ...f.filter, to: '2026-11-05T12:01:00.000Z' }), []);
    assert.equal(f.ctx.db.get<{ n: number }>('SELECT count(*) n FROM events')!.n, 0);
    await writeFile(join(f.root, 'base.txt'), 'base'); git(f.root, 'add', '.'); git(f.root, 'commit', '-qm', 'Base a remover');
    const removed = git(f.root, 'rev-parse', 'HEAD');
    await writeFile(join(f.root, 'rebase.txt'), 'rebase'); git(f.root, 'add', '.'); git(f.root, 'commit', '-qm', 'Rebase');
    const beforeRebase = git(f.root, 'rev-parse', 'HEAD'); await scanCommits(f.ctx, root);
    git(f.root, '-c', 'user.name=Test', '-c', 'user.email=test@example.test', 'rebase', '--onto', first, removed);
    await scanCommits(f.ctx, root);
    assert.equal(listCommits(f.ctx, f.filter).find((c) => c.sha === beforeRebase)!.origins[0]!.reachable, false);
    assert.notEqual(git(f.root, 'rev-parse', 'HEAD'), beforeRebase);
    const nested = join(f.root, 'subdir'); await mkdir(nested);
    registerProjectRoot(f.ctx, { projectName: 'Subpasta', projectId: randomUUID(), path: nested, deviceId: f.ctx.config.deviceId });
    const nestedRoot = listProjects(f.ctx).flatMap((p) => p.roots).find((r) => r.path === realpathSync(nested))!;
    await scanCommits(f.ctx, nestedRoot);
    assert.equal(listCommits(f.ctx, { ...f.filter, projectIds: [nestedRoot.projectId!] }).every((c) => c.files.length === 0), true);
  } finally { await f.close(); }
});
